// Inlines worlds-boot.js into index.html's <head> with the current hashed chunk list.
// Run after rebuilding assets/worlds/js (see source/worlds/README.md).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const dir = "assets/worlds/js";
const files = readdirSync(dir).filter(name => name.endsWith(".js"));
const entry = "stage.js";
// Entry first (it is also what the loader executes), then the shared engine, then worlds.
const order = name => (name === entry ? 0 : name.startsWith("stage-") ? 1 : 2);
const chunks = files.sort((a, b) => order(a) - order(b) || a.localeCompare(b)).map(name => `${dir}/${name}`);
const stamp = Date.now().toString(36);
chunks[0] = `${chunks[0]}?v=${stamp}`;

const source = readFileSync("worlds-boot.js", "utf8")
  .replace(/^\/\*[\s\S]*?\*\/\n/, "")             // drop the file header comment
  .replace("/*CHUNKS*/[]", JSON.stringify(chunks))
  .trim();
const block = `<!-- worlds-boot:start (generated by scripts/update-worlds-boot.mjs) -->\n  <script>${source}</script>\n  <!-- worlds-boot:end -->`;

const html = readFileSync("index.html", "utf8");
const marker = /<!-- worlds-boot:start[\s\S]*?<!-- worlds-boot:end -->/;
const next = marker.test(html)
  ? html.replace(marker, block)
  : html.replace(/  <script src="worlds-boot\.js\?v=[^"]*" async><\/script>/, `  ${block}`);
if (next === html && !marker.test(html)) throw new Error("worlds-boot placeholder not found in index.html");
writeFileSync("index.html", next);
console.log(`worlds boot inlined with ${chunks.length} chunks`);
